#!/usr/bin/env python3
"""Write engrave/src/api/pid_support.generated.inc: the Pids each element type handles.

`describe` must say which properties an element type accepts, and the engine has no
such registry: a type's support comes from the `case Pid::X:` labels of its class's
`getProperty` and `setProperty` (src/engraving/dom/*.cpp), from its base classes, and
from the `ElementStyle` lists a class installs into itself (styled properties reach
the element through the style, not through a getter).

What the scan does, per type:

 1. element types: `DECLARE_CLASSOF(ElementType::X)` in a class declaration.  A few
    classes take their type as a constructor argument instead (`Staff`,
    `BracketItem`, `Parenthesis`); they are read from `Class::Class(...) :
    Base(ElementType::X, ...)`.
 2. properties: every `Class::getProperty` / `Class::setProperty` definition in
    src/engraving, and every `ElementStyle` list it installs or reads.  A type
    inherits the properties of its class's base classes up to `EngravingObject`.
 3. settable: the Pid appears in a `setProperty` switch and is not in DENY, the
    hand-kept list of structural Pids that only structural operations may set.

The xml name of a type is the one in TConv's element type table (typesconv.cpp), so
the names here are the names an MSCX file and the public API use.

    tools/gen_pid_support.py             rewrite the .inc
    tools/gen_pid_support.py --check     exit 1 when the checked-in .inc is stale

Output is deterministic: types sorted by name, Pids sorted by name, LF endings.
"""

import argparse
import re
import sys
from pathlib import Path

# Structural Pids: they follow from where an element sits, not from an edit of the
# element.  PITCH and the tonal pitch classes must go through EditNote's pitch edit.
DENY = {
    "GENERATED",
    "PITCH",
    "SELECTED",
    "TICK",
    "TPC1",
    "TPC2",
    "TRACK",
}

HEADER = """\
// Generated by tools/gen_pid_support.py from the engine sources.  Do not edit.
//
// Type names are TConv's xml element type names; a type's Pids are the ones its
// getProperty/setProperty implementations handle, directly or through a base class
// or an ElementStyle list.  A class that does not hand an unknown Pid to its base
// (`Staff`, `Score`) inherits nothing.  A Pid is settable when setProperty takes it
// and it is not in the generator's deny list (structural Pids: {deny}).
//
// type_pids rows are sorted by type name; each covers a run of pid_support, sorted
// by Pid name.  pid_names renames the Pids whose xml name is empty or already taken.
"""


def strip_code(text):
    """Blank out comments and literals, keeping every offset in place."""
    char_literal = re.compile(r"'(?:\\.|[^\\'])*'")
    out = list(text)
    i = 0
    n = len(text)
    while i < n:
        c = text[i]
        if c == "/" and i + 1 < n and text[i + 1] == "/":
            while i < n and text[i] != "\n":
                out[i] = " "
                i += 1
        elif c == "/" and i + 1 < n and text[i + 1] == "*":
            out[i] = out[i + 1] = " "
            i += 2
            while i + 1 < n and not (text[i] == "*" and text[i + 1] == "/"):
                out[i] = " " if text[i] != "\n" else "\n"
                i += 1
            if i + 1 < n:
                out[i] = out[i + 1] = " "
                i += 2
        elif c == "\"":
            out[i] = " "
            i += 1
            while i < n and text[i] != "\"":
                if text[i] == "\\":
                    out[i] = " "
                    i += 1
                if i < n:
                    out[i] = " " if text[i] != "\n" else "\n"
                    i += 1
            if i < n:
                out[i] = " "
                i += 1
        elif c == "'" and char_literal.match(text, i):
            end = char_literal.match(text, i).end()
            for j in range(i, end):
                out[j] = " "
            i = end
        else:
            i += 1
    return "".join(out)


def blocks(text, start):
    """(open, close) offsets of the braces body that starts at or after `start`."""
    open_index = text.index("{", start)
    depth = 0
    for i in range(open_index, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return open_index, i
    raise ValueError("unbalanced braces")


def class_spans(text):
    """[(start, end, class name or None)] for every brace block, nested ones included."""
    head = re.compile(r"\b(\w+)::(~?\w+)\s*\(")
    spans = []
    stack = []
    last_break = 0
    for i, c in enumerate(text):
        if c == "{":
            matches = list(head.finditer(text[last_break:i]))
            owner = matches[-1].group(1) if matches else (stack[-1][1] if stack else None)
            stack.append((i, owner))
            last_break = i + 1
        elif c == "}":
            if stack:
                start, owner = stack.pop()
                spans.append((start, i, owner))
            last_break = i + 1
    return spans


def owner_at(spans, offset):
    best = None
    for start, end, owner in spans:
        if start <= offset <= end and owner and (best is None or start > best[0]):
            best = (start, owner)
    return best[1] if best else None


def read_sources(root):
    """{relative path: stripped text} for every engine source, in sorted order."""
    sources = {}
    for path in sorted((root / "src" / "engraving").rglob("*")):
        if path.suffix in (".h", ".cpp"):
            text = path.read_text(encoding="utf-8", errors="replace")
            sources[path.relative_to(root).as_posix()] = strip_code(text)
    return sources


def parse_classes(sources):
    """class -> {"bases": [...], "types": [...]}."""
    classes = {}
    head = re.compile(r"\b(?:class|struct)\s+(\w+)\s*(?:final)?\s*(?::([^{;]*))?\{")
    for text in sources.values():
        for match in head.finditer(text):
            bases = []
            for part in (match.group(2) or "").split(","):
                names = re.findall(r"\w+", re.sub(r"\b(?:public|protected|private|virtual)\b", " ", part))
                if names:
                    bases.append(names[-1])
            classes.setdefault(match.group(1), {"bases": [], "types": []})["bases"] = bases
    for text in sources.values():
        for match in head.finditer(text):
            start, end = blocks(text, match.end() - 1)
            types = [t for t in re.findall(r"DECLARE_CLASSOF\(ElementType::(\w+)\)", text[start:end]) if t != "INVALID"]
            if types:
                classes[match.group(1)]["types"] = types
    return classes


def parse_properties(sources):
    """class -> {"get": {Pid}, "set": {Pid}, "get_forwards", "set_forwards"}.

    The forwards flags record whether the class's getProperty and setProperty hand a
    Pid they do not know to their base: a class that reads its own Pids and answers
    PropertyValue() otherwise (`Staff`, `Score`) inherits nothing, although the base
    chain says it could.
    """
    properties = {}
    definition = re.compile(
        r"^[ \t]*[\w][\w:<>,*&\s]*?\b(\w+)::(getProperty|setProperty)\s*\([^)]*\)\s*"
        r"(?:const\s*)?(?:noexcept\s*)?(?:override\s*)?\{",
        re.M)
    for text in sources.values():
        for match in definition.finditer(text):
            start, end = blocks(text, match.end() - 1)
            body = text[start:end]
            kind = "get" if match.group(2) == "getProperty" else "set"
            entry = properties.setdefault(
                match.group(1), {"get": set(), "set": set(), "get_forwards": True, "set_forwards": True})
            entry[kind].update(re.findall(r"case Pid::(\w+)\s*:", body))
            if not re.search(r"\w+::" + match.group(2) + r"\s*\(", body):
                entry[kind + "_forwards"] = False
    return properties


def parse_styles(sources):
    """{(file, style variable): {Pid}} for the ElementStyle lists of the classes."""
    styles = {}
    definition = re.compile(r"\bElementStyle\s+(\w+)\s*\{")
    for path, text in sources.items():
        for match in definition.finditer(text):
            start, end = blocks(text, match.end() - 1)
            styles.setdefault((path, match.group(1)), set()).update(
                re.findall(r"\{\s*Sid::\w+\s*,\s*Pid::(\w+)\s*\}", text[start:end]))
    return styles


def parse_style_owners(sources):
    """{(file, style variable): {class}} for the classes that install or read a list."""
    owners = {}
    names = {}
    for path, text in sources.items():
        defined = set(re.findall(r"\bElementStyle\s+(\w+)\s*\{", text))
        if not defined:
            continue
        patterns = {name: re.compile(r"\b" + name + r"\b") for name in defined}
        spans = class_spans(text)
        for name, pattern in patterns.items():
            for match in pattern.finditer(text):
                before = text[max(0, match.start() - 40):match.start()]
                if re.search(r"ElementStyle\s*$", before):
                    continue                                # the definition itself
                owner = owner_at(spans, match.start())
                if owner:
                    owners.setdefault((path, name), set()).add(owner)
    return owners


def parse_constructor_types(sources):
    """class -> {ElementType} for classes that pass their type to the base constructor."""
    found = {}
    definition = re.compile(
        r"^[ \t]*(\w+)::\1\s*\([^)]*\)\s*(?::[^{;]*)?\bEngravingItem\s*\(\s*ElementType::(\w+)", re.M)
    for text in sources.values():
        for match in definition.finditer(text):
            found.setdefault(match.group(1), set()).add(match.group(2))
    return found


def parse_type_names(root):
    """ElementType member -> xml name, from TConv's element type table."""
    text = (root / "src" / "engraving" / "types" / "typesconv.cpp").read_text(encoding="utf-8")
    return dict(re.findall(r'Item\{\s*ElementType::(\w+),\s*"([^"]*)"', text))


def parse_pid_names(root):
    """(Pid -> xml name, Pid -> the name the API uses).

    The engine's property table gives a few Pids the same xml name (fourteen share
    "subtype") and gives some none at all, so a name is only an identifier while it
    is unique: the first Pid with a name keeps it, the rest keep their Pid name.
    """
    text = (root / "src" / "engraving" / "dom" / "property.cpp").read_text(encoding="utf-8")
    rows = re.findall(
        r'\{\s*Pid::(\w+)\s*,\s*P_TYPE::\w+\s*,\s*PropertyGroup::\w+\s*,\s*(?:true|false)\s*,\s*"([^"]*)"', text)
    xml_names = dict(rows)
    api_names = {}
    taken = set()
    for pid, xml_name in rows:
        name = xml_name if xml_name and xml_name not in taken else pid
        if name in taken:
            raise ValueError(f"Pid::{pid} has no unique name: {name}")
        api_names[pid] = name
        taken.add(name)
    return xml_names, api_names


def build(root):
    sources = read_sources(root)
    classes = parse_classes(sources)
    properties = parse_properties(sources)
    styles = parse_styles(sources)
    style_owners = parse_style_owners(sources)
    for key, owners in style_owners.items():
        for owner in owners:
            entry = properties.setdefault(
                owner, {"get": set(), "set": set(), "get_forwards": True, "set_forwards": True})
            entry["get"] |= styles[key]
    for name, types in parse_constructor_types(sources).items():
        if len(types) == 1 and not classes.get(name, {}).get("types"):
            classes.setdefault(name, {"bases": [], "types": []})["types"] = list(types)

    type_names = parse_type_names(root)
    type_of_class = {}
    for name, entry in classes.items():
        for element_type in entry["types"]:
            type_of_class[name] = element_type

    def inherited(name, seen=()):
        """The get/set Pid sets of a class and, where it forwards, of its bases."""
        entry = properties.get(name, {"get": set(), "set": set(), "get_forwards": True, "set_forwards": True})
        get, settable = set(entry["get"]), set(entry["set"])
        for base in classes.get(name, {}).get("bases", []):
            if base in seen or base not in classes:
                continue
            base_get, base_set = inherited(base, seen + (name,))
            if entry["get_forwards"]:
                get |= base_get
            if entry["set_forwards"]:
                settable |= base_set
        return get, settable

    rows = []
    for name, element_type in type_of_class.items():
        xml_name = type_names.get(element_type)
        if not xml_name:
            continue
        get, settable = inherited(name)
        pids = sorted(get | settable)
        rows.append((xml_name, [(pid, pid in settable and pid not in DENY) for pid in pids]))
    rows.sort()

    pid_names = parse_pid_names(root)
    xml_names, api_names = pid_names
    named = {pid for _, pids in rows for pid, _ in pids}
    missing = sorted(named - set(api_names))
    if missing:
        raise ValueError(f"no name for {missing}")
    # Only the Pids whose name is not their xml name need a row of their own.
    overrides = sorted((pid, name) for pid, name in api_names.items() if name != xml_names.get(pid, ""))
    return rows, overrides


def wrap(entries, indent="    ", width=118):
    """Greedy line wrap of Pid entries, so a diff touches one line per change."""
    lines = []
    line = indent
    for entry in entries:
        if len(line) + len(entry) + 1 > width and line.strip():
            lines.append(line.rstrip())
            line = indent
        line += entry + " "
    if line.strip():
        lines.append(line.rstrip())
    return lines


def render(rows, overrides):
    lines = [HEADER.format(deny=", ".join(sorted(DENY)))]
    lines.append("constexpr TypePids type_pids[] = {")
    first = 0
    for name, pids in rows:
        lines.append(f'    {{ "{name}", {first}, {len(pids)} }},')
        first += len(pids)
    lines.append("};\n")
    lines.append("constexpr PidEntry pid_support[] = {")
    for name, pids in rows:
        lines.append(f"    // {name}")
        lines += wrap([f"{{ Pid::{pid}, {str(settable).lower()} }}," for pid, settable in pids])
    lines.append("};\n")
    lines.append("// The Pids whose name is not their xml name: the first claimant of an xml")
    lines.append("// name keeps it, the rest use the Pid name.")
    lines.append("constexpr PidName pid_names[] = {")
    for pid, name in overrides:
        lines.append(f'    {{ Pid::{pid}, "{name}" }},')
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent,
                        help="the engrave checkout (default: this script's repository)")
    parser.add_argument("--check", action="store_true", help="fail when the checked-in file is stale")
    args = parser.parse_args()

    target = args.root / "engrave" / "src" / "api" / "pid_support.generated.inc"
    text = render(*build(args.root))
    if args.check:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != text:
            print(f"stale: {target} does not match tools/gen_pid_support.py; regenerate it", file=sys.stderr)
            return 1
        return 0
    target.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
